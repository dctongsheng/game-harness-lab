"""Game-neutral contracts. Adapters own rules; the runtime owns all model calls."""
from __future__ import annotations
from typing import Protocol


class GameSession(Protocol):
    def snapshot(self) -> dict: ...
    def candidates(self) -> list[dict[str, str]]: ...
    def step(self, action_id: str) -> dict: ...
    def close(self) -> None: ...


class GameAdapter(Protocol):
    id: str
    name: str
    rules_version: str
    rules: str
    score_spec: dict
    defaults: dict
    opponent_policy: dict[str, str] | None

    def create(self, seed: int, config: dict) -> GameSession: ...
    def validate_config(self, config: dict) -> None: ...
    def scope_config(self, config: dict) -> dict: ...
    def context(self, config: dict) -> dict: ...
